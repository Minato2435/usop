function optionLike(options, re, avoid) {
  return (options ?? []).find((o) => re.test(o) && !(avoid && avoid.test(o)))
}

function fillAnswers(fields, decision, studentName, reviewerName, feedback) {
  const answers = {}
  const notDone = new Set()
  for (const f of fields) {
    const step = f.id.match(/^step-(\d+)$/)
    if (step) {
      const bad = decision === 'rejected' ? chance(0.45) : decision === 'revisionRequested' ? chance(0.2) : chance(0.05)
      const done = optionLike(f.options, /^done$/i)
      const nd = optionLike(f.options, /not\s*done/i)
      const v = bad && nd ? nd : (done ?? f.options?.[0] ?? '')
      if (v) answers[f.id] = v
      if (bad && nd) notDone.add(step[1])
    }
  }
  for (const f of fields) {
    const rem = f.id.match(/^remark-(\d+)$/)
    if (rem && notDone.has(rem[1])) answers[f.id] = pick(STEP_REMARKS)
    else if (f.id.startsWith('rating-')) {
      if (f.type === 'rating') {
        const max = f.maxRating ?? 5
        answers[f.id] = String(decision === 'approved' ? randInt(Math.ceil(max * 0.7), max) : randInt(1, Math.ceil(max / 2)))
      } else if (f.options?.length) {
        const good = optionLike(f.options, /(satisf|competent|meets|good|above|pass|independ)/i, /(un|not|below|fail)/i)
        const poor = optionLike(f.options, /(unsatisf|below|not|fail|border)/i)
        answers[f.id] = decision === 'approved' ? (good ?? f.options[0]) : (poor ?? f.options[f.options.length - 1])
      }
    } else if (f.id === 'feedback') answers[f.id] = feedback
    else if (f.id === 'student-ack') answers[f.id] = studentName
    else if (f.id === 'assessor-sign') answers[f.id] = reviewerName
  }
  return answers
}

