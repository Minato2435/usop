const MAX_DATA_URL = 148_000 // the app's own per-image cap is 150_000 chars
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'usop-demo-'))
const HAS_SIPS = process.platform === 'darwin'

function jpegDataUrl(pngPath, maxDim) {
  const out = path.join(tmpDir, `${path.basename(pngPath)}-${Math.round(rng() * 1e9)}.jpg`)
  for (const [q, dim] of [[72, maxDim], [60, maxDim], [50, maxDim], [55, 700], [45, 600]]) {
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', String(q), '-Z', String(dim), pngPath, '--out', out], { stdio: 'ignore' })
    const url = `data:image/jpeg;base64,${fs.readFileSync(out).toString('base64')}`
    if (url.length <= MAX_DATA_URL) return url
  }
  return null
}

const cache = new Map()
function photo(kind, variant) {
  const key = `p:${kind}:${variant}`
  if (!cache.has(key)) {
    const p = path.join(tmpDir, `${kind}-${variant}.png`)
    fs.writeFileSync(p, renderPhoto(kind, SEED * 100 + variant * 17 + kind.length))
    cache.set(key, jpegDataUrl(p, 900))
  }
  return cache.get(key)
}
function sketch(kind, variant) {
  const key = `s:${kind}:${variant}`
  if (!cache.has(key)) cache.set(key, `data:image/png;base64,${renderSketch(kind, SEED * 31 + variant * 7 + kind.length).toString('base64')}`)
  return cache.get(key)
}

function findScreenshots() {
  if (!USE_SCREENSHOTS || !HAS_SIPS) return []
  const dirs = [ROOT, path.join(ROOT, 'attaching references')]
  const out = []
  for (const dir of dirs) {
    if (!fs.existsSync(dir)) continue
    for (const f of fs.readdirSync(dir)) {
      if (!/^Screenshot.*\.png$/i.test(f)) continue
      const full = path.join(dir, f)
      try {
        const info = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', full], { encoding: 'utf8' })
        const w = Number(info.match(/pixelWidth: (\d+)/)?.[1]), h = Number(info.match(/pixelHeight: (\d+)/)?.[1])
        if (w >= 600 && h > 0 && w / h >= 0.9 && w / h <= 2.2) out.push(full)
      } catch {
        /* skip unreadable */
      }
    }
  }
  return out
}
