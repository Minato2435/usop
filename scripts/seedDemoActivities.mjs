// One-off seed script — NOT wired into the app, run manually. Fills several
// students of one college with realistic SSL activities (10–20 each, spread
// over their different departments), so My Activity, the PDF export, the
// faculty/HOD queues and the portfolio all have real-looking data:
//
//   - each activity is logged against a real skill from that department's SSL
//     logs (global + the college's own, minus skills switched off for the
//     college), with that skill's DOPS form
//   - written description (headings, steps, reflection) per activity
//   - attachments: clinical-style photos (X-ray, ECG printout, fundus,
//     dermoscopy, suture pad — matched to the department), sometimes one of
//     the interface screenshots in this repo, and a hand-drawn labelled
//     sketch (ECG / sutures / heart / lungs / eye / skin layers) — all
//     generated by scripts/lib/demoImages.mjs. Photos are JPEG and the sketch
//     is PNG, exactly like the app saves them.
//   - a realistic mix of outcomes: approved (with filled DOPS checklist,
//     feedback, remarks, rating, competency level), some approved by the HOD
//     instead of the assigned faculty, revision requested, resubmitted after
//     revision, rejected, awaiting review, and the odd draft
//   - first / repeat / remedial attempt types follow the student's own history
//   - departments with no faculty (or no HOD) get one created
//     (fac1@kl.com / hod1@kl.com …, password 123456)
//
// Every activity it writes carries seedTag: 'demo-activities'. A student who
// already has demo activities is skipped — pass --reset to delete their demo
// activities (only those) and write fresh ones.
//
// Images are uploaded to Firebase Storage as the student (same paths as the
// app: submissions/{studentId}/{submissionId}/{imageId}.jpg|png) — deploy
// storage.rules first.
//
// Run from the repo root on a Mac (photos are converted with the built-in
// `sips`). ALWAYS try --plan first (reads only, writes nothing):
//   SEED_ADMIN_EMAIL=you@example.com SEED_ADMIN_PASSWORD=your-password \
//     node scripts/seedDemoActivities.mjs --plan
// Options:
//   --college "kasuburu"     part of the college name (default kasuburu)
//   --students 6             how many students (default 6, spread across years)
//   --rolls "KAS/Y1/0101,KAS/Y2/0101"   exact students instead of --students
//   --min 10 --max 20        activities per student (default 10–20)
//   --seed 7                 change for a different random mix
//   --no-screenshots         don't use the repo's interface screenshots as photos
//   --reset                  replace these students' previous demo activities
//   --student-password 123456   the students' password (default 123456)
//
// Uses the existing rules unchanged: each activity is created signed in AS
// the student, then the review outcome is added with the admin login.
//
// Writes to the live test project in .env (usop-38351 — a throwaway test DB).

