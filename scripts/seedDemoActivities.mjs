function kindsFor(deptName) {
  const n = deptName.toLowerCase()
  if (/ophthal|eye/.test(n)) return { photos: ['fundus'], sketches: ['eye'] }
  if (/derma|skin|venere/.test(n)) return { photos: ['dermoscopy'], sketches: ['skin'] }
  if (/surg|ortho|obst|gyn|anaes/.test(n)) return { photos: ['suturePad', 'xray'], sketches: ['sutures'] }
  if (/medicine|cardio|physio/.test(n)) return { photos: ['ecgPaper', 'xray'], sketches: ['ecg', 'heart'] }
  if (/anatom/.test(n)) return { photos: ['xray'], sketches: ['heart', 'lungs'] }
  if (/pulmo|respir|chest|tuberc/.test(n)) return { photos: ['xray'], sketches: ['lungs'] }
  if (/paediat|pediat/.test(n)) return { photos: ['xray', 'ecgPaper'], sketches: ['lungs', 'heart'] }
  return { photos: ['xray', 'ecgPaper', 'fundus', 'dermoscopy', 'suturePad'], sketches: ['ecg', 'heart', 'lungs', 'sutures', 'eye', 'skin'] }
}

